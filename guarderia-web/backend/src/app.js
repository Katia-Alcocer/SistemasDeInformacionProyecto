import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import {fileURLToPath} from 'node:url';
import {securityConfig} from './config/env.js';
import {HttpError,idParam} from './utils/http.js';
import {authService} from './modules/auth/auth.service.js';
import {authRoutes} from './modules/auth/auth.routes.js';
import {usuariosService} from './modules/usuarios/usuarios.service.js';
import {usuariosRoutes} from './modules/usuarios/usuarios.routes.js';
import {gruposService} from './modules/grupos/grupos.service.js';
import {gruposRoutes} from './modules/grupos/grupos.routes.js';
import {authenticate,allowRoles,csrf} from './middlewares/security.js';
import {openapi} from './routes/openapi.js';
import {admissionOpenapi} from './routes/openapi.s2.js';
import {receptionOpenapi} from './routes/openapi.s3.js';
import {menoresService} from './modules/menores/menores.service.js';
import {menoresRoutes} from './modules/menores/menores.routes.js';
import {auditoriaRoutes} from './modules/menores/auditoria.routes.js';
import {preinscripcionesService} from './modules/preinscripciones/preinscripciones.service.js';
import {preinscripcionesRoutes} from './modules/preinscripciones/preinscripciones.routes.js';
import {tutoresService} from './modules/tutores/tutores.service.js';
import {personasRoutes,tutoresRoutes} from './modules/tutores/tutores.routes.js';
import {documentosService} from './modules/documentos/documentos.service.js';
import {documentosRoutes,identidadRoutes} from './modules/documentos/documentos.routes.js';
import {recetasService} from './modules/recetas/recetas.service.js';
import {recetasRoutes,dosificadorRoutes} from './modules/recetas/recetas.routes.js';
import {insumosService} from './modules/insumos/insumos.service.js';
import {insumosRoutes} from './modules/insumos/insumos.routes.js';
import {recepcionService} from './modules/recepcion/recepcion.service.js';
import {recepcionRoutes} from './modules/recepcion/recepcion.routes.js';
import {aulasService} from './modules/aulas/aulas.service.js';
import {aulasRoutes} from './modules/aulas/aulas.routes.js';
import {inventoryOpenapi} from './routes/openapi.s4.js';
import {medicamentosService} from './modules/medicamentos/medicamentos.service.js';
import {medicamentosRoutes} from './modules/medicamentos/medicamentos.routes.js';
import {comedorService} from './modules/comedor/comedor.service.js';
import {comedorRoutes} from './modules/comedor/comedor.routes.js';
import {diningOpenapi} from './routes/openapi.comedor.js';
import {salidasService} from './modules/salidas/salidas.service.js';
import {salidasRoutes} from './modules/salidas/salidas.routes.js';
import {exitOpenapi} from './routes/openapi.s5.js';
import {enfermeriaService} from './modules/enfermeria/enfermeria.service.js';
import {enfermeriaRoutes} from './modules/enfermeria/enfermeria.routes.js';
import {nursingOpenapi} from './routes/openapi.enfermeria.js';
import {retardosService} from './modules/retardos/retardos.service.js';
import {retardosRoutes} from './modules/retardos/retardos.routes.js';
import {delayOpenapi} from './routes/openapi.retardos.js';
import {approvalsOpenapi} from './routes/openapi.aprobaciones.js';
import {autoridadService} from './modules/autoridad/autoridad.service.js';
import {autoridadRoutes} from './modules/autoridad/autoridad.routes.js';
import {authorityOpenapi} from './routes/openapi.autoridad.js';
import {pagosService} from './modules/pagos/pagos.service.js';
import {cuotasRoutes,pagosRoutes,prorrogasRoutes} from './modules/pagos/pagos.routes.js';
import {financeOpenapi} from './routes/openapi.finanzas.js';
export function createApp(database, config = securityConfig()) {
  const app = express();
  app.disable('x-powered-by');
  app.use(helmet());
  app.use(cors({origin:config.origin,credentials:true}));
  app.use((req,_res,next)=>{if(req.get('Origin') && req.get('Origin')!==config.origin)return next(new HttpError(403,'ORIGIN_DENIED','Origen no permitido'));next();});
  app.use(cookieParser());
  app.use(express.json({limit:'32kb'}));
  app.set('view engine','ejs');
  app.set('views',fileURLToPath(new URL('../views/ejs',import.meta.url)));
  app.use((_req,res,next)=>{res.set('Cache-Control','no-store');next();});
  const auth=authService(database,config);
  app.use('/api/v1/enfermeria',authenticate(auth),allowRoles('ADMIN','ENFERMERIA','RECEPCION'),csrf(config),enfermeriaRoutes(enfermeriaService(database,config)));
  app.use('/api/v1/comedor',authenticate(auth),allowRoles('ADMIN','ENFERMERIA','EDUCADORA'),csrf(config),comedorRoutes(comedorService(database,config)));
  app.use('/api/v1/medicamentos',authenticate(auth),allowRoles('ADMIN','ENFERMERIA','EDUCADORA'),csrf(config),medicamentosRoutes(medicamentosService(database,config)));
  app.get('/api/v1/openapi.json',(_req,res)=>res.json(financeOpenapi(authorityOpenapi(approvalsOpenapi(delayOpenapi(nursingOpenapi(exitOpenapi(diningOpenapi(inventoryOpenapi(receptionOpenapi(admissionOpenapi(openapi))))))))))));
  const groups=gruposService(database);
  app.use('/api/v1/auth',authRoutes(auth,config));
  const guard=[authenticate(auth),allowRoles('ADMIN'),csrf(config)];
  const childRecords=menoresService(database);
  app.use('/api/v1/admin/auditoria-dif',...guard,auditoriaRoutes(childRecords));
  app.get('/reportes/expediente/:id',...guard,idParam,async(q,r)=>r.render('expediente',{reporte:await childRecords.printableReport(q.params.id,q.session.user.id_usuario)}));
  const finances=pagosService(database,config);
  app.use('/api/v1/cuotas',...guard,cuotasRoutes(finances));
  app.use('/api/v1/pagos',...guard,pagosRoutes(finances));
  app.use('/api/v1/prorrogas',...guard,prorrogasRoutes(finances));
  app.get('/reportes/pagos/:id',...guard,idParam,async(q,r)=>r.render('pago',{pago:await finances.receipt(q.params.id,q.session.user.id_usuario)}));
  const authority=autoridadService(database,config);
  app.use('/api/v1/autoridad',...guard,autoridadRoutes(authority));
  app.get('/reportes/autoridad/:id',...guard,idParam,async(q,s)=>s.render('autoridad',{reporte:await authority.detail(q.params.id,q.session.user.id_usuario)}));
  app.use('/api/v1/usuarios',...guard,usuariosRoutes(usuariosService(database)));
  app.use('/api/v1/grupos',...guard,gruposRoutes(groups));
  const admissionGuard=[authenticate(auth),allowRoles('ADMIN','RECEPCION'),csrf(config)];
  app.use('/api/v1/retardos',...admissionGuard,retardosRoutes(retardosService(database,config)));
  const documents=documentosService(database,config);
  const tutors=tutoresService(database);
  app.use('/api/v1/admin/menores',documentosRoutes(documents,guard));
  app.use('/api/v1/admin/menores',...admissionGuard,menoresRoutes(childRecords));
  app.use('/api/v1/preinscripciones',...guard,preinscripcionesRoutes(preinscripcionesService(database)));
  app.use('/api/v1/personas',identidadRoutes(documents,guard));
  app.use('/api/v1/personas',...admissionGuard,personasRoutes(tutors));
  app.use('/api/v1/menores',...admissionGuard,tutoresRoutes(tutors));
  const medical=recetasService(database,config);
  const medicalGuard=[authenticate(auth),allowRoles('ADMIN','ENFERMERIA'),csrf(config)];
  app.use('/api/v1/recetas',authenticate(auth),allowRoles('ADMIN','ENFERMERIA','RECEPCION'),csrf(config),dosificadorRoutes(medical));
  app.use('/api/v1/recetas',...medicalGuard,recetasRoutes(medical,documents));
  const inventory=insumosService(database,config);
  app.use('/api/v1/insumos',authenticate(auth),allowRoles('ADMIN','RECEPCION','EDUCADORA'),csrf(config),insumosRoutes(inventory));
  app.use('/api/v1/aulas',authenticate(auth),allowRoles('ADMIN','EDUCADORA'),csrf(config),aulasRoutes(aulasService(database,config),inventory));
  app.use('/api/v1/recepcion',...admissionGuard,recepcionRoutes(recepcionService(database,config)));
  app.use('/api/v1/recepcion',...admissionGuard,salidasRoutes(salidasService(database,config)));
  app.get('/reportes/grupos',...guard,async(_req,res)=>res.render('grupos',{grupos:await groups.list()}));
  app.get('/api/v1/health', async (_req,res) => {
    try {
      await database.query('SELECT 1');
      res.json({data:{status:'ok',database:'connected'},message:'API y base de datos disponibles',error:null});
    } catch {
      res.status(503).json({data:null,message:'Base de datos no disponible',error:{code:'DATABASE_UNAVAILABLE'}});
    }
  });
  app.use((_req,res) => res.status(404).json({data:null,message:'Ruta no encontrada',error:{code:'NOT_FOUND'}}));
  app.use((err,_req,res,_next) => {
    const status = err.status || (err.code==='ER_DUP_ENTRY'?409:err.type==='entity.parse.failed'?400:err.type==='entity.too.large'?413:500);
    res.status(status).json({data:null,message:status===500?'Error interno':err instanceof HttpError?err.message:status===409?'El correo, código o CURP ya está registrado':'Solicitud inválida',error:{code:err instanceof HttpError?err.code:status===409?'DUPLICATE':status===500?'INTERNAL_ERROR':'INVALID_REQUEST'}});
  });
  return app;
}
